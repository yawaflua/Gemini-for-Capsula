function initialLocale(): Locale {
  const saved = typeof localStorage === 'undefined' ? null : localStorage.getItem('marusya-plugins.locale')
  if (saved === 'ru' || saved === 'en') return saved
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

export const locale = writable<Locale>(initialLocale())

locale.subscribe((value) => {
  if (typeof localStorage !== 'undefined') localStorage.setItem('marusya-plugins.locale', value)
  if (typeof document !== 'undefined') document.documentElement.lang = value
})

export const t = derived(locale, ($locale) => (source: string, variables: Record<string, string | number> = {}) => {
  let value = $locale === 'en' ? (english[source] ?? source) : source
  Object.entries(variables).forEach(([key, replacement]) => {
    value = value.replaceAll(`{${key}}`, String(replacement))
  })
  return value
})

export function setLocale(value: Locale) {
  locale.set(value)
}

export function translate(source: string, variables: Record<string, string | number> = {}) {
  let value = get(locale) === 'en' ? (english[source] ?? source) : source
  Object.entries(variables).forEach(([key, replacement]) => {
    value = value.replaceAll(`{${key}}`, String(replacement))
  })
  return value
}

export function intlLocale() {
  return get(locale) === 'en' ? 'en-US' : 'ru-RU'
}
